const fs=require('node:fs'),path=require('node:path'),crypto=require('node:crypto'),assert=require('node:assert/strict');
const {apply,hash}=require('./apply-child-upgrade.cjs');
const base=path.resolve(process.argv[2]),packageRoot=path.resolve(process.argv[3]);
const work=path.resolve('build/release-upgrade-tests',crypto.randomUUID()),target=path.join(work,'installed');
fs.mkdirSync(work,{recursive:true});fs.cpSync(base,target,{recursive:true});
const config=path.join(target,'data/goose/config/config.yaml'),original=path.join(target,'workspace/original.txt');
fs.mkdirSync(path.dirname(config),{recursive:true});fs.mkdirSync(path.dirname(original),{recursive:true});
fs.writeFileSync(config,'GOOSE_PROVIDER: synthetic-no-account\nGOOSE_MODEL: preserved-model\nGOOSE_AUTO_COMPACT_THRESHOLD: 0.15\nGOOSE_AUTO_COMPACT_TOKEN_LIMIT: 40000\nGOOSE_COMPACT_TARGET_TOKENS: 6000\nextensions: {}\n');
fs.writeFileSync(original,'SYNTHETIC ORIGINAL MANUSCRIPT');
const before=[config,original].map(hash);
const receipt=apply({packageRoot,target,backupRoot:path.join(work,'backups')});
assert.deepEqual([config,original].map(hash),before);
const manifest=JSON.parse(fs.readFileSync(path.join(packageRoot,'upgrade.json')));
assert.equal(JSON.parse(fs.readFileSync(path.join(target,'agent.json'))).version,manifest.toVersion);
const rel='app/BOSS-win32-x64/resources/bin/goose.exe';
assert.equal(hash(path.join(target,rel)),manifest.files.find(f=>f.path===rel).sha256);
assert(receipt.protectedDataUnchangedBeforeLaunch);
const report={passed:true,fromVersion:manifest.fromVersion,toVersion:manifest.toVersion,realProgramUpgradeApplied:true,modelAndCustomBudgetAndManuscriptPreserved:true,nativeEngineReplaced:true,backupCreated:fs.existsSync(receipt.backup),realModelCalled:false,liveInstallationChanged:false};
fs.writeFileSync('.release-work/upgrade-0.1.2-verification.json',JSON.stringify(report,null,2));console.log(JSON.stringify(report));
